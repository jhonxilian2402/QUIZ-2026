import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { getEnv } from "../config/env";

/**
 * Storage abstraction.
 *
 * The application stores bytes through this interface, never against a specific
 * vendor. The database keeps only metadata and a storage key, so swapping the
 * implementation does not touch the data model.
 *
 * The default implementation persists bytes on local disk (dev/staging-friendly)
 * and a swap to S3/Supabase/Cloudinary requires only this file.
 */

export type PutResult = {
  storageKey: string;
  /** Whether the bytes are actually durable. */
  persisted: boolean;
};

export interface StorageProvider {
  readonly id: string;
  put(input: {
    userId: string;
    filename: string;
    mimeType: string;
    body: Uint8Array;
  }): Promise<PutResult>;
  get(storageKey: string): Promise<Uint8Array | null>;
  remove(storageKey: string): Promise<void>;
  signedUrl(storageKey: string, expiresInSeconds: number): Promise<string | null>;
}

/** Local-disk storage. Deterministic key layout under `${STORAGE_DIR}`. */
class LocalDiskStorageProvider implements StorageProvider {
  readonly id = "local-disk";

  private root(): string {
    return path.join(process.cwd(), getEnv().STORAGE_DIR);
  }

  private resolve(storageKey: string): string | null {
    const full = path.join(this.root(), storageKey);
    if (!full.startsWith(this.root() + path.sep) && full !== this.root()) {
      // Path traversal guard: keys are generated by us, never by users.
      return null;
    }
    return full;
  }

  async put(input: {
    userId: string;
    filename: string;
    mimeType: string;
    body: Uint8Array;
  }): Promise<PutResult> {
    const storageKey = `users/${input.userId}/files/${randomUUID()}/original`;
    const full = this.resolve(storageKey);
    if (!full) throw new Error("Invalid storage key.");
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, input.body, { flag: "wx" });
    return { storageKey, persisted: true };
  }

  async get(storageKey: string): Promise<Uint8Array | null> {
    const full = this.resolve(storageKey);
    if (!full) return null;
    try {
      const buffer = await readFile(full);
      return new Uint8Array(buffer);
    } catch {
      return null;
    }
  }

  async remove(storageKey: string): Promise<void> {
    const full = this.resolve(storageKey);
    if (!full) return;
    await rm(full, { force: true, recursive: true });
  }

  async signedUrl(): Promise<string | null> {
    // No public URL is exposed for private objects; the dev server streams
    // through the authenticated /api/files/:id/content route instead.
    return null;
  }
}

let active: StorageProvider | null = null;

export function getStorage(): StorageProvider {
  active ??= new LocalDiskStorageProvider();
  return active;
}

/** Test hook: replace or null the active provider. */
export function setStorage(provider: StorageProvider | null): void {
  active = provider;
}

export const storageStatus = {
  provider: "local-disk",
  durable: true,
  reason: "Bytes are persisted under STORAGE_DIR (default .data/storage).",
} as const;
